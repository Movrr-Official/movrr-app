export function partnerText(locale: PartnerLocale, text: string): string {
  if (locale === "en") return text;
  const imported = text.match(/^Imported (\d+) code\(s\)\.$/);
  if (imported) return `${imported[1]} codes ge\u00efmporteerd.`;
  return partnerDutch[text] ?? text;
}
